/**
 * Celebration fanfare / chords when chosen student is revealed!
 */
export function playVictorySound() {
  if (!soundEnabled) return;
  try {
    const ctx = getAudioContext();
    if (!ctx) return;

    // A celebratory C Major chord arpeggio: C5, E5, G5, C6
    const notes = [523.25, 659.25, 783.99, 1046.5];
    const delays = [0, 0.09, 0.18, 0.28];
    const durations = [0.25, 0.25, 0.35, 0.6];

    notes.forEach((freq, idx) => {
      const startTime = ctx.currentTime + delays[idx];
      const duration = durations[idx];

      const osc = ctx.createOscillator();
      const gain = ctx.createGain();

      osc.type = idx === notes.length - 1 ? 'triangle' : 'sine';
      osc.frequency.setValueAtTime(freq, startTime);

      gain.gain.setValueAtTime(0.001, startTime);
      gain.gain.linearRampToValueAtTime(0.2, startTime + 0.02);
      gain.gain.exponentialRampToValueAtTime(0.0001, startTime + duration);

      osc.connect(gain);
      gain.connect(ctx.destination);

      osc.start(startTime);
      osc.stop(startTime + duration);
    });
  } catch {
    // AudioContext failure fallback
  }
}

